"""Render the configuration reference from the code.

`docs/CONFIGURATION-REFERENCE.md` is generated, never edited: it lists every config key and its
default (from `kindi.config.DEFAULTS`) and every `KINDI_*` environment variable that `kindi/` reads.
A new key or switch therefore cannot be missing from the reference - `python -m
kindi.config_reference --check` (and `tests/test_config_reference.py`) fails until the file is
regenerated with `python -m kindi.config_reference`.

A config key also has an environment form, `KINDI_<KEY>`; those are covered by the config table and
are not repeated in the environment table.
"""
import ast
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CONFIG_PY = os.path.join(HERE, "config.py")
REFERENCE = os.path.join(ROOT, "docs", "CONFIGURATION-REFERENCE.md")
ENV_NAME = re.compile(r"^KINDI_[A-Z0-9_]+$")

HEADER = """\
# Configuration reference

<!-- Generated by `python -m kindi.config_reference`; do not edit this file by hand. -->

Every setting Kindi reads, taken from the code itself: the config keys and their defaults from
`kindi/config.py` (`config.DEFAULTS`), and every `KINDI_*` environment variable read under
`kindi/`. `tests/test_config_reference.py` fails when either list changes and this file is not
regenerated.

Precedence (later wins): built-in defaults < config file < environment (`KINDI_<KEY>`) <
command-line flags. `docs/CONFIGURATION.md` is the prose guide, with the notes on the commonly
used switches.

Regenerate with:

```sh
python -m kindi.config_reference
```

## Config keys

Each key can also be set from the environment as `KINDI_<KEY>` (for example `KINDI_CTX=8192`).
"""

ENV_HEADER = """\
## Environment-only variables

These have no config key. The default is the code's own fallback (empty: unset); the last column
is where it is read, which is where the full description lives.
"""


def _read(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read().replace("\r\n", "\n")


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def _trailing_comment(line):
    """the `# ...` note at the end of a DEFAULTS line, which is the key's description"""
    i = line.find("#")
    return line[i + 1:].strip() if i >= 0 else ""


def _group_above(lines, i):
    """the standalone comment line directly above a key, if the key starts a new group"""
    j = i - 1
    while j >= 0:
        text = lines[j].strip()
        if not text:
            j -= 1
            continue
        return text.lstrip("#").strip() if text.startswith("#") else None
    return None


def config_keys():
    """`kindi.config.DEFAULTS`: every key, its type, default and the comment beside it"""
    src = _read(CONFIG_PY)
    tree = ast.parse(src)
    lines = src.splitlines()
    defaults = None
    sets = {"INT_KEYS": set(), "FLOAT_KEYS": set(), "PATH_KEYS": set()}
    for stmt in tree.body:
        if not isinstance(stmt, ast.Assign) or not isinstance(stmt.value, ast.Dict):
            if isinstance(stmt, ast.Assign) and stmt.targets and isinstance(stmt.targets[0], ast.Name) \
                    and stmt.targets[0].id in sets:
                sets[stmt.targets[0].id] = set(ast.literal_eval(stmt.value))
            continue
        if any(isinstance(t, ast.Name) and t.id == "DEFAULTS" for t in stmt.targets):
            defaults = stmt.value
    if defaults is None:
        raise SystemExit("kindi: config.DEFAULTS not found in %s" % CONFIG_PY)
    out, group = [], ""
    for key, value in zip(defaults.keys, defaults.values):
        name = key.value
        found = _group_above(lines, key.lineno - 1)
        if found:
            group = found
        kind = ("int" if name in sets["INT_KEYS"] else "float" if name in sets["FLOAT_KEYS"]
                else "path" if name in sets["PATH_KEYS"] else "string")
        out.append({"key": name, "type": kind, "default": value.value, "group": group,
                    "description": _trailing_comment(lines[key.lineno - 1])})
    return out


def _environ(node):
    return (isinstance(node, ast.Attribute) and node.attr == "environ"
            and isinstance(node.value, ast.Name) and node.value.id == "os")


def _default_text(node, src):
    """a literal string's value, or the default expression as it is written"""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return " ".join((ast.get_source_segment(src, node) or "").split())


def env_vars(paths=None):
    """name -> {defaults: [...], sites: [...]} for every `KINDI_*` read under `kindi/`"""
    found = {}
    for path in (paths if paths is not None else sorted(glob.glob(os.path.join(HERE, "*.py")))):
        src = _read(path)
        for node in ast.walk(ast.parse(src)):
            name = default = None
            if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and node.func.attr == "get" and _environ(node.func.value)
                    and node.args and isinstance(node.args[0], ast.Constant)
                    and isinstance(node.args[0].value, str)):
                name = node.args[0].value
                if len(node.args) > 1:
                    default = _default_text(node.args[1], src)
            elif (isinstance(node, ast.Subscript) and _environ(node.value)
                    and isinstance(node.slice, ast.Constant) and isinstance(node.slice.value, str)):
                name = node.slice.value
            if not name or not ENV_NAME.match(name):
                continue
            entry = found.setdefault(name, {"defaults": [], "sites": []})
            site = (os.path.basename(path), node.lineno)
            if site not in entry["sites"]:
                entry["sites"].append(site)
            if default is not None and default not in entry["defaults"]:
                entry["defaults"].append(default)
    for entry in found.values():
        entry["sites"].sort(key=lambda s: (s[0], s[1]))
    return found


def _default_cell(values):
    if not values:
        return "(unset)"
    if len(values) == 1 and values[0] == "":
        return "(empty)"
    return " or ".join("`%s`" % _cell(v) if v else "(empty)" for v in values)


def _site_cell(sites):
    first = "`kindi/%s:%d`" % sites[0]
    return first if len(sites) == 1 else "%s (+%d more)" % (first, len(sites) - 1)


def render(env_paths=None):
    keys = config_keys()
    envs = env_vars(env_paths)
    lines = HEADER.splitlines()
    group = None
    for k in keys:
        if k["group"] != group:
            group = k["group"]
            lines += ["", "### %s" % group, "", "| key | type | default | meaning |", "|---|---|---|---|"]
        default = "`%s`" % _cell(k["default"]) if k["default"] else "(empty)"
        lines.append("| `%s` | %s | %s | %s |" % (k["key"], k["type"], default, _cell(k["description"])))
    lines += [""] + ENV_HEADER.splitlines() + ["", "| variable | default | read in |", "|---|---|---|"]
    skip = {"KINDI_" + k["key"].upper() for k in keys}
    for name in sorted(set(envs) - skip):
        lines.append("| `%s` | %s | %s |" % (name, _default_cell(envs[name]["defaults"]),
                                             _site_cell(envs[name]["sites"])))
    return "\n".join(lines) + "\n"


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        current = _read(REFERENCE) if os.path.exists(REFERENCE) else ""
        if current != text:
            sys.stderr.write("kindi: %s is stale; run `python -m kindi.config_reference`\n" % REFERENCE)
            return 1
        return 0
    with open(REFERENCE, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    sys.stdout.write("wrote %s (%d config keys, %d environment reads)\n" % (
        REFERENCE, len(config_keys()), len(env_vars())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
